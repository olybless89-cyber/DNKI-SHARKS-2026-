"use client";

import { useState } from "react";
import { useMe } from "@/components/app-shell";
import { Alert, Button, ErrorNote, Field, PageTitle } from "@/components/ui";
import { type ApiError, api, fmtDate, useApi } from "@/lib/api";

export default function Security() {
  const me = useMe();
  const [setup, setSetup] = useState<{ qrDataUrl: string; secret: string } | null>(null);
  const [recovery, setRecovery] = useState<string[] | null>(null);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<ApiError | null>(null);
  const [msg, setMsg] = useState<string | null>(null);
  const sessions = useApi<{
    items: { id: string; created_at: string; last_seen_at: string; user_agent: string | null; current: boolean }[];
  }>("/auth/sessions");

  async function run(fn: () => Promise<void>) {
    setBusy(true);
    setErr(null);
    setMsg(null);
    try {
      await fn();
    } catch (e) {
      setErr(e as ApiError);
    } finally {
      setBusy(false);
    }
  }

  return (
    <>
      <PageTitle title="Account security" sub={me.user.email} />
      <div className="max-w-2xl space-y-12">
        <ErrorNote error={err} />
        {msg && <Alert tone="success">{msg}</Alert>}

        <section className="space-y-4">
          <h2 className="font-display text-3xl font-semibold">Two-step verification</h2>
          {me.mfa.enrollmentRequired && !recovery && (
            <Alert tone="warn" title="Set up two-step verification to continue">
              Staff accounts must use an authenticator app before accessing any administrative tools.
            </Alert>
          )}
          {recovery ? (
            <div className="space-y-4">
              <Alert tone="success" title="Two-step verification is on">
                Save these recovery codes somewhere safe. Each works once if you lose your phone. They will not be shown again.
              </Alert>
              <ul className="grid grid-cols-2 gap-2 border-2 border-ink p-4 font-display text-xl tracking-wider">
                {recovery.map((c) => (
                  <li key={c}>{c}</li>
                ))}
              </ul>
              <Button onClick={() => window.location.assign(me.privileged ? "/admin" : "/portal")}>I have saved my codes</Button>
            </div>
          ) : me.mfa.enabled ? (
            <p>Two-step verification is on for this account.</p>
          ) : setup ? (
            <form
              className="space-y-4"
              onSubmit={(e) => {
                e.preventDefault();
                const code = new FormData(e.currentTarget).get("code");
                void run(async () => {
                  const r = await api<{ recoveryCodes: string[] }>("/auth/mfa/enable", { body: { code } });
                  setRecovery(r.recoveryCodes);
                });
              }}
            >
              <p>
                Scan this code with an authenticator app (for example Google Authenticator, Microsoft Authenticator or 1Password),
                then enter the 6-digit code it shows.
              </p>
              {/* biome-ignore lint/performance/noImgElement: data URL generated by the API */}
              <img
                src={setup.qrDataUrl}
                alt="Authenticator setup code"
                width={200}
                height={200}
                className="border-2 border-ink"
              />
              <p className="text-sm text-slate">
                Can't scan? Enter this key manually: <span className="font-mono break-all">{setup.secret}</span>
              </p>
              <Field label="6-digit code" name="code" inputMode="numeric" autoComplete="one-time-code" required />
              <Button type="submit" busy={busy}>
                Turn on two-step verification
              </Button>
            </form>
          ) : (
            <Button busy={busy} onClick={() => run(async () => setSetup(await api("/auth/mfa/setup", { method: "POST" })))}>
              Set up two-step verification
            </Button>
          )}
        </section>

        <section className="space-y-4">
          <h2 className="font-display text-3xl font-semibold">Change password</h2>
          <form
            className="space-y-4"
            onSubmit={(e) => {
              e.preventDefault();
              const form = e.currentTarget;
              const f = new FormData(form);
              void run(async () => {
                await api("/auth/password/change", { body: { currentPassword: f.get("current"), newPassword: f.get("next") } });
                form.reset();
                setMsg("Password changed. Your other sessions were signed out.");
                void sessions.reload();
              });
            }}
          >
            <Field label="Current password" name="current" type="password" autoComplete="current-password" required />
            <Field
              label="New password"
              name="next"
              type="password"
              autoComplete="new-password"
              required
              minLength={12}
              hint="At least 12 characters."
            />
            <Button type="submit" variant="secondary" busy={busy}>
              Change password
            </Button>
          </form>
        </section>

        <section className="space-y-4">
          <h2 className="font-display text-3xl font-semibold">Signed-in devices</h2>
          <ul className="divide-y-2 divide-line border-y-2 border-line">
            {sessions.data?.items.map((s) => (
              <li key={s.id} className="py-3">
                <p className="font-semibold">{s.current ? "This device" : (s.user_agent?.slice(0, 80) ?? "Unknown device")}</p>
                <p className="text-sm text-slate">Last active {fmtDate(s.last_seen_at)}</p>
              </li>
            ))}
          </ul>
          <Button
            variant="secondary"
            busy={busy}
            onClick={() =>
              run(async () => {
                await api("/auth/sessions/revoke-others", { method: "POST" });
                setMsg("Other devices were signed out.");
                void sessions.reload();
              })
            }
          >
            Sign out other devices
          </Button>
        </section>
      </div>
    </>
  );
}
